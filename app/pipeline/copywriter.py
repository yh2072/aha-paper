_PROMPT = """你是小红书科普爆款操盘手。根据下面的口播稿，产出发布物料。

{domain}

{weakness}

标题是这四条杠杆的主战场——上面每个例子本身就是一个标题。
产出标题前先想：这篇论文能压中哪条杠杆，然后照那条的句式去写。

只输出 JSON：
{{"intro": "约500字的小红书简介",
  "title_options": ["标题1", "标题2", "标题3"],
  "title_levers": ["标题1压的杠杆", "标题2压的杠杆", "标题3压的杠杆"]}}

要求：
- intro：小红书爆款排版——
  · 每句不超过 15 字，多短句多换行，拒绝大段文字
  · 穿插 emoji 视觉锚点（🧠 💡 ❌ ✅ 📌），重点结论用 📌 或 ✅ 起头
  · 必须完整保留口播稿里的"实操步骤/落地公式"（收藏价值核心，逐条列出）
  · 结尾先抛一个引发评论互动的钩子问题，再带 4~6 个话题标签（#脑科学 格式）
  · 450~550 字（不含标签）
- title_options：3 个不超过 15 字的标题，不要书名号。硬性要求：
  · 【三个必须分别压不同的杠杆】比如一个走懒惰（"三个动作/五分钟/直接抄"）、
    一个走害怕或厌恶失去（"做错这件事，白费了多少年"）、一个走从众或反常识
    （"记性好的人都在偷偷做这件事"）。三个都是同一路数的算不合格
  · 【句式也必须错开】光换杠杆标签不算数。三个要分属三种句式：
    一个疑问句（"为什么你…""XX真的XX吗"）、一个判断句（"XX真不是你懒"
    "别再XX了"）、一个数字/结论句（"XX秒就XX""三步让XX"）。
    出现两个标题主干句式雷同（比如都是"XX一乱，卡顿32毫秒"），算不合格
  · 每个标题都要能落到具体的人和具体的结果，不要"大脑的奥秘"这种空标题
  · 【底线】标题里的数字和结论必须来自口播稿，不许为了好看编。
    从众式标题（"XX的人都在用"）必须对应稿中真实的实验组/高分组
  · 语气平视，不恐吓：可以"咱们都踩过这个坑"，不许"再不看就晚了"

同时输出每个标题压的是哪条杠杆，方便人工挑选。

论文原标题：{paper_title}

口播稿：
{script}"""


def generate_social_copy(script: str, paper_title: str) -> dict:
    out = llm.chat_json([{"role": "user", "content": _PROMPT.format(
        script=script, paper_title=paper_title, weakness=HUMAN_WEAKNESS, domain=DOMAIN_STYLE)}])
    titles = [str(t).strip()[:15] for t in out.get("title_options", [])][:3]
    levers = [str(x).strip() for x in out.get("title_levers", [])][:3]
    return {"intro": str(out.get("intro", "")).strip(), "title_options": titles,
            "title_levers": levers}
